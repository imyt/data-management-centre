"""Database access: the declarative base, column mixins and one session per request (ADR 0005).

Routes take a `SessionDep`. The request's work runs in one transaction that commits when the
route returns and rolls back if it raises. The commit happens before the response is sent, so a
failed commit is a 500, never a 200.
"""

import uuid
from collections.abc import Iterator
from contextlib import contextmanager
from datetime import datetime
from typing import Annotated

from fastapi import Depends, Request
from sqlalchemy import Connection, DateTime, Engine, MetaData, create_engine, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, Session, mapped_column, sessionmaker

# Stable constraint names, so Alembic can find and drop them later.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base for every module's models. Each module's tables live in its own schema."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDv7PrimaryKey:
    """`id` generated by Postgres 18's uuidv7(): time-ordered, so inserts stay in index order."""

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, server_default=text("uuidv7()"))


class Timestamps:
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class Database:
    """Hands out sessions bound to an engine or, in tests, to a connection inside a transaction."""

    def __init__(self, bind: Engine | Connection) -> None:
        # create_savepoint: bound to a connection that is already in a transaction (tests), a
        # session's commit releases a savepoint instead of committing the outer transaction.
        self._sessions = sessionmaker(
            bind=bind, expire_on_commit=False, join_transaction_mode="create_savepoint"
        )

    @contextmanager
    def transaction(self) -> Iterator[Session]:
        """One unit of work: commits on exit, rolls back if the block raises."""
        with self._sessions.begin() as session:
            yield session


def create_database_engine(url: str) -> Engine:
    return create_engine(url, pool_pre_ping=True)


def _get_session(request: Request) -> Iterator[Session]:
    database: Database | None = request.app.state.database
    if database is None:
        raise RuntimeError("No database: set DMC_DATABASE_URL (see backend/.env.example)")
    with database.transaction() as session:
        yield session


# scope="function" ends the transaction when the route returns, before the response is sent.
SessionDep = Annotated[Session, Depends(_get_session, scope="function")]
